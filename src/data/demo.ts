const clone = <T,>(x: T): T => JSON.parse(JSON.stringify(x));

export interface Scenario {
  id: string;
  title: string;
  hint: string;
  /** Данные сценария, или строка — «сырой» файл, который проходит через импорт */
  build: () => BureauData | string;
}

